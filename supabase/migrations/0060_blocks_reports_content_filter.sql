-- Books & Runs — safety layer: block users, report users, and a content
-- filter on public text (display names, bios, club/tournament names).
-- Run this once in the Supabase SQL editor, after 0001–0059.
--
--   1. user_blocks + block_user()/unblock_user()/my_blocks()/is_blocked_pair()
--      Blocking removes any friendship, drops the blocked account's unseen
--      requests, and from then on:
--        • the two accounts can't become friends (trigger on friendships —
--          covers friend requests AND friend-code links),
--        • friend-code lookup of the blocker returns "no such code",
--        • neither can invite the other to a game (the `mp` function checks
--          is_blocked_pair), and the blocker no longer sees the blocked
--          account's emotes (RLS on mp_emotes, migration 0061),
--        • the leaderboard RPCs (0063) hide them from each other.
--      Nothing tells the blocked account it happened.
--   2. user_reports + report_user() — one report per (reporter, target,
--      kind), rate-limited, with a snapshot of the reported name/bio so a
--      later edit can't erase the evidence. No read policy at all: rows are
--      read only from the dashboard / service role. report_profile_photo()
--      (0025/0049) now files into the same table, so there is one queue.
--   3. content_blocklist + content_flagged() + triggers — server-side
--      enforcement of the same rules as src/safety/contentFilter.ts (the
--      client pre-check). The list below is GENERATED by
--      scripts/gen-blocklist-sql.mjs from src/safety/blocklist.ts; a unit
--      test fails if this file drifts from it. Only NEW values are checked
--      (a name/bio that is unchanged is never re-validated), and the
--      trigger fails open: an unexpected error in the check lets the write
--      through rather than locking anyone out of saving their profile.
--
-- Reviewing reports (SQL editor):
--   select r.created_at, r.kind, r.reason, r.note, r.context,
--          le.display_name as reported_name, r.snapshot
--   from public.user_reports r
--   left join public.leaderboard_entries le on le.user_id = r.reported_user_id
--   where r.status = 'open' order by r.created_at desc;

-- ─────────────────────────────────────────────────────────────────────────
-- 1. blocks
-- ─────────────────────────────────────────────────────────────────────────

create table if not exists public.user_blocks (
  blocker_id uuid not null references auth.users (id) on delete cascade,
  blocked_id uuid not null references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  check (blocker_id <> blocked_id)
);

create index if not exists user_blocks_blocked on public.user_blocks (blocked_id);

alter table public.user_blocks enable row level security;

-- You can read your own block list. Nobody can read who blocked THEM, and
-- all writes go through the RPCs below.
drop policy if exists "user_blocks: blocker read" on public.user_blocks;
create policy "user_blocks: blocker read" on public.user_blocks
  for select using (auth.uid() = blocker_id);

-- Either direction. Internal helper (security definer so RLS-restricted
-- callers can still ask it); not granted to clients.
create or replace function public.is_blocked_pair(a uuid, b uuid)
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1 from public.user_blocks
    where (blocker_id = a and blocked_id = b) or (blocker_id = b and blocked_id = a)
  );
$$;

revoke execute on function public.is_blocked_pair(uuid, uuid) from anon, public, authenticated;

create or replace function public.block_user(p_user uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare me uuid := auth.uid();
begin
  if me is null then raise exception 'not authenticated'; end if;
  if p_user is null or p_user = me then raise exception 'invalid target'; end if;
  if not exists (select 1 from auth.users where id = p_user) then raise exception 'no such user'; end if;

  perform public.mp_bump_rate_limit('block_user', 60);

  insert into public.user_blocks (blocker_id, blocked_id) values (me, p_user)
    on conflict do nothing;

  -- Unfriend / drop any pending request in either direction.
  delete from public.friendships
    where (requester_id = me and addressee_id = p_user)
       or (requester_id = p_user and addressee_id = me);
  -- Clear their unseen friend requests / invites from my inbox.
  delete from public.mp_events
    where user_id = me and actor_id = p_user and seen_at is null
      and kind in ('friend_request', 'friend_accepted', 'game_request', 'nudge');
end;
$$;

create or replace function public.unblock_user(p_user uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare me uuid := auth.uid();
begin
  if me is null then raise exception 'not authenticated'; end if;
  delete from public.user_blocks where blocker_id = me and blocked_id = p_user;
end;
$$;

create or replace function public.my_blocks()
returns table (user_id uuid, display_name text, blocked_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare me uuid := auth.uid();
begin
  if me is null then raise exception 'not authenticated'; end if;
  return query
    select b.blocked_id, le.display_name, b.created_at
    from public.user_blocks b
    left join public.leaderboard_entries le on le.user_id = b.blocked_id
    where b.blocker_id = me
    order by b.created_at desc;
end;
$$;

revoke execute on function public.block_user(uuid), public.unblock_user(uuid), public.my_blocks()
  from anon, public;
grant execute on function public.block_user(uuid), public.unblock_user(uuid), public.my_blocks()
  to authenticated;

-- Blocked pairs can't (re)connect. Covers mp_send_friend_request and
-- mp_add_friend_by_code without redefining either. The message is neutral
-- and does not reveal who blocked whom.
create or replace function public.friendships_block_guard()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.is_blocked_pair(new.requester_id, new.addressee_id) then
    raise exception 'You can''t connect with this player' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

drop trigger if exists friendships_block_guard on public.friendships;
create trigger friendships_block_guard
  before insert or update on public.friendships
  for each row execute function public.friendships_block_guard();

-- Friend-code lookup: a blocked pair can't find each other. (Body is 0013's
-- plus the block filter.)
create or replace function public.mp_lookup_friend_code(code text)
returns table (user_id uuid, display_name text)
language plpgsql
security definer
set search_path = public
as $$
declare
  me uuid := auth.uid();
begin
  if me is null then raise exception 'not authenticated'; end if;
  perform public.mp_bump_rate_limit('friend_code_lookup', 60);
  return query
    select p.id, le.display_name
    from public.profiles p
    left join public.leaderboard_entries le on le.user_id = p.id
    where upper(p.friend_code) = upper(trim(code))
      and not public.is_blocked_pair(me, p.id)
    limit 1;
end;
$$;

revoke execute on function public.mp_lookup_friend_code(text) from anon, public;
grant execute on function public.mp_lookup_friend_code(text) to authenticated;

