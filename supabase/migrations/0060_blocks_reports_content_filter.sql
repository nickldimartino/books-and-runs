-- Mirrors foldText() in src/safety/contentFilter.ts: NFKC, lower-case,
-- ß/æ/œ expansion, then a 1:1 accent-fold and leet-fold translate.
create or replace function public.content_fold(t text)
returns text
language sql
immutable
as $$
  select translate(
    replace(replace(replace(lower(normalize(coalesce(t, ''), NFKC)), 'ß', 'ss'), 'æ', 'ae'), 'œ', 'oe'),
    'àáâãäåāăąçćčďđèéêëēėęěìíîïīįłñńňòóôõöøōőŕřśšşťùúûüūůűųýÿźżžё013457@$',
    'aaaaaaaaacccddeeeeeeeeiiiiiilnnnoooooooorrssstuuuuuuuuyyzzzеoieastas'
  );
$$;

-- "f u c k" / "f.u.c.k": runs of 3+ single-letter words become one word.
create or replace function public.content_words(folded text)
returns text[]
language plpgsql
immutable
as $$
declare
  out_ text[] := '{}';
  buf text := '';
  n int := 0;
  w text;
begin
  for w in select x from regexp_split_to_table(folded, '[^[:alnum:]]+') x where x <> '' loop
    if w ~ '^[a-z]$' then
      buf := buf || w;
      n := n + 1;
    else
      if n >= 3 then out_ := out_ || buf;
      elsif n > 0 then out_ := out_ || regexp_split_to_array(buf, '');
      end if;
      buf := '';
      n := 0;
      out_ := out_ || w;
    end if;
  end loop;
  if n >= 3 then out_ := out_ || buf;
  elsif n > 0 then out_ := out_ || regexp_split_to_array(buf, '');
  end if;
  return out_;
end;
$$;

-- Returns null when the text is fine, else 'empty' | 'profanity' |
-- 'impersonation' | 'link'. kind: 'name' | 'bio' | 'title'.
create or replace function public.content_flagged(t text, kind text default 'name')
returns text
language plpgsql
stable
as $$
declare
  folded text;
  words text[];
  sq text;
begin
  if t is null or btrim(t) = '' then
    return case when kind = 'bio' then null else 'empty' end;
  end if;

  folded := public.content_fold(btrim(t));
  words := public.content_words(folded);
  sq := regexp_replace(
    array_to_string(array(select x from regexp_split_to_table(folded, '[^[:alnum:]]+') x where x <> ''), ''),
    '([a-z])\1{2,}', '\1\1', 'g');

  if exists (
    select 1 from public.content_blocklist b
    where b.mode = 'sub' and b.term <> '' and position(b.term in sq) > 0
  ) then
    return 'profanity';
  end if;

  -- w3: runs of 3+ letters cut to 2; the fully-collapsed comparison only
  -- applies to words that were actually stretched (fuuuck, not shiitake).
  if exists (
    select 1
    from public.content_blocklist b
    cross join lateral (
      select regexp_replace(x, '([a-z])\1{2,}', '\1\1', 'g') as w3,
             (x ~ '([a-z])\1{2,}') as stretched
      from unnest(words) as x
    ) u
    where b.term <> '' and (
      (b.mode = 'stem' and (
        left(u.w3, length(b.term)) = b.term
        or (u.stretched and left(regexp_replace(u.w3, '([a-z])\1+', '\1', 'g'), length(b.term_loose)) = b.term_loose)))
      or (b.mode = 'word' and (
        u.w3 = b.term
        or (u.stretched and regexp_replace(u.w3, '([a-z])\1+', '\1', 'g') = b.term_loose)))
    )
  ) then
    return 'profanity';
  end if;

  if kind <> 'bio' and exists (
    select 1 from public.content_blocklist b
    where b.term <> '' and (
      (b.mode = 'res_exact' and sq = b.term)
      or (b.mode = 'res_contains' and position(b.term in sq) > 0)
      or (b.mode = 'res_prefix' and left(sq, length(b.term)) = b.term))
  ) then
    return 'impersonation';
  end if;

  if t ~* '(https?://|www\.|[a-z0-9-]+\.(com|net|org|io|gg|ly|me|co|app|xyz|ru|cn)\y|@[a-z0-9-]+\.[a-z]{2,})' then
    return 'link';
  end if;

  return null;
end;
$$;

revoke execute on function public.content_fold(text), public.content_words(text), public.content_flagged(text, text)
  from anon, public, authenticated;

create or replace function public.content_guard_message(issue text, kind text)
returns text
language sql
immutable
as $$
  select case
    when issue = 'link' then 'Links aren''t allowed here'
    when issue = 'impersonation' then 'That name is reserved'
    when kind = 'bio' then 'That bio isn''t allowed'
    else 'That name isn''t allowed'
  end;
$$;

revoke execute on function public.content_guard_message(text, text) from anon, public, authenticated;

create or replace function public.leaderboard_content_guard()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare issue text;
begin
  if new.display_name is not null and (tg_op = 'INSERT' or new.display_name is distinct from old.display_name) then
    issue := null;
    begin issue := public.content_flagged(new.display_name, 'name');
    exception when others then issue := null; end;
    if issue is not null and issue <> 'empty' then
      raise exception '%', public.content_guard_message(issue, 'name') using errcode = 'P0001';
    end if;
  end if;
  if new.bio is not null and (tg_op = 'INSERT' or new.bio is distinct from old.bio) then
    issue := null;
    begin issue := public.content_flagged(new.bio, 'bio');
    exception when others then issue := null; end;
    if issue is not null then
      raise exception '%', public.content_guard_message(issue, 'bio') using errcode = 'P0001';
    end if;
  end if;
  return new;
end;
$$;

