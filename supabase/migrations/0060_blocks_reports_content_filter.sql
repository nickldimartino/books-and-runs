create table if not exists public.user_reports (
  id uuid primary key default gen_random_uuid(),
  -- Kept (set null) if the reporter later deletes their account, so a report
  -- doesn't vanish with them; removed with the reported account.
  reporter_id uuid references auth.users (id) on delete set null,
  reported_user_id uuid not null references auth.users (id) on delete cascade,
  kind text not null check (kind in ('name', 'bio', 'photo', 'behavior', 'other')),
  reason text not null check (reason in
    ('offensive', 'harassment', 'impersonation', 'cheating', 'spam', 'inappropriate_photo', 'other')),
  note text check (note is null or char_length(note) <= 280),
  -- Where it was filed from: profile | friends | mp_game | club | tournament | leaderboard
  context text check (context is null or char_length(context) <= 32),
  game_id uuid,
  -- The reported account's public text when it was reported.
  snapshot jsonb not null default '{}'::jsonb,
  status text not null default 'open' check (status in ('open', 'reviewed', 'actioned', 'dismissed')),
  created_at timestamptz not null default now()
);

create unique index if not exists user_reports_once
  on public.user_reports (reporter_id, reported_user_id, kind) where reporter_id is not null;
create index if not exists user_reports_open on public.user_reports (status, created_at desc);

alter table public.user_reports enable row level security;
-- Deliberately NO policies: not readable or writable from any client.

-- Bring over any existing photo reports (0025) so there's a single queue.
insert into public.user_reports (reporter_id, reported_user_id, kind, reason, note, created_at)
select reporter_id, reported_user_id, 'photo', 'inappropriate_photo', reason, created_at
from public.profile_photo_reports
on conflict do nothing;

create or replace function public.report_user(
  p_reported_user_id uuid,
  p_kind text,
  p_reason text,
  p_note text default null,
  p_game_id uuid default null,
  p_context text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me uuid := auth.uid();
  snap jsonb;
begin
  if me is null then raise exception 'not authenticated'; end if;
  if p_reported_user_id is null or p_reported_user_id = me then raise exception 'cannot report yourself'; end if;
  if p_kind not in ('name', 'bio', 'photo', 'behavior', 'other') then raise exception 'invalid report'; end if;
  if p_reason not in ('offensive', 'harassment', 'impersonation', 'cheating', 'spam', 'inappropriate_photo', 'other') then
    raise exception 'invalid report';
  end if;
  if not exists (select 1 from auth.users where id = p_reported_user_id) then raise exception 'no such user'; end if;

  perform public.mp_bump_rate_limit('report_user', 20);

  select jsonb_build_object(
    'display_name', le.display_name,
    'bio', le.bio,
    'avatar_kind', le.avatar_kind,
    'avatar_photo_path', le.avatar_photo_path
  ) into snap
  from public.leaderboard_entries le where le.user_id = p_reported_user_id;

  insert into public.user_reports (reporter_id, reported_user_id, kind, reason, note, context, game_id, snapshot)
    values (
      me, p_reported_user_id, p_kind, p_reason,
      nullif(left(btrim(coalesce(p_note, '')), 280), ''),
      left(p_context, 32), p_game_id, coalesce(snap, '{}'::jsonb)
    )
    on conflict (reporter_id, reported_user_id, kind) where reporter_id is not null do nothing;
end;
$$;

revoke execute on function public.report_user(uuid, text, text, text, uuid, text) from anon, public;
grant execute on function public.report_user(uuid, text, text, text, uuid, text) to authenticated;

